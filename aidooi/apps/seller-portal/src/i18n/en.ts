type Widen<T> = {
  [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends Record<string, string>
      ? { [P in keyof T[K]]: string }
      : T[K];
};
export type Catalogue = Widen<typeof en>;
/** Keys whose value is a plain string (the ones `fmt` and direct rendering use). */
export type StringKey = {
  [K in keyof Catalogue]: Catalogue[K] extends string ? K : never;
}[keyof Catalogue];
